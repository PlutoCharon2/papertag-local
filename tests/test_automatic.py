def payload(paper):
    return {'paper_id': paper['id'], 'document_hash': paper['file_hash'], 'ontology_version': 1, 'schema_version': 2,
            'title': 'Test', 'authors': [], 'year': None, 'doi': '', 'paper_type': 'unknown', 'summary': 'Generated by GPT',
            'tags': [{'label_id': 'new_acoustic', 'evidence': [{'block_id': '', 'page': 1, 'quote': 'acoustic levitation'}]}],
            'claims': [], 'suggestions': [], 'new_labels': [{'key': 'new_acoustic', 'dimension': 'application', 'name': '声学悬浮', 'definition': '以声学悬浮为应用对象。'}]}


def transport(monkeypatch, data, callback=None):
    calls = []
    def fake(workspace, images, prompt, schema, timeout, model, cancel):
        assert len(images) == 1 and images[0].is_file()
        assert 'PDF' in prompt
        calls.append(1)
        if callback:
            callback()
        raw = json.dumps(data, ensure_ascii=False)
        (workspace / 'response.json').write_text(raw, encoding='utf-8')
        return raw
    monkeypatch.setattr(codex_service, 'infer', fake)
    return calls


def test_new_gpt_label_is_saved_and_cache_prevents_repeat(library, monkeypatch):
    client, pid, paper = library
    calls = transport(monkeypatch, payload(paper))
    job = ai.enqueue(pid)
    assert ai.enqueue(pid) == job
    ai.analyze_one(job)
    assert calls == [1]
    assert client.get('/api/ai/jobs').json()[0]['status'] == 'completed'
    assert any(l['name'] == '声学悬浮' and l['paper_count'] == 1 for l in client.get('/api/ontology').json()['labels'])
    assert ai.enqueue(pid) is None
    assert len(client.get(f'/api/papers/{pid}').json()['history']) == 1


