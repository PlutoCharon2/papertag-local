@pytest.mark.parametrize('rejected', [False, True])
def test_claim_labels_populate_paper_and_facets_without_reviving_rejection(library, monkeypatch, rejected):
    client, pid, paper = library
    data = payload(paper)
    data['tags'] = []
    data['new_labels'] = []
    data['claims'] = [{'id': 'claim1', 'kind': 'theoretical_result', 'text': 'Model provided statement',
                       'method': 'Unknown', 'system': 'Unknown', 'conditions': [], 'target': '', 'result_form': '',
                       'scope': '', 'residual': '', 'label_ids': ['asymptotic', 'bounded'],
                       'evidence': [{'page': 1, 'quote': 'Only neighborhood convergence.'}]}]
    if rejected:
        client.post(f'/api/papers/{pid}/decision', json={'label_id': 'asymptotic', 'decision': 'rejected'})
    calls = transport(monkeypatch, data)
    ai.analyze_one(ai.enqueue(pid))
    stored = client.get(f'/api/papers/{pid}').json()
    assert client.get('/api/ai/jobs').json()[0]['status'] == 'completed'
    assert {t['label_id'] for t in stored['analysis']['tags']} == {'asymptotic', 'bounded'}
    assert stored['analysis']['tags'][0]['evidence'][0]['page'] == 1
    effective = {t['label_id'] for t in stored['tags']}
    assert ('asymptotic' in effective) is not rejected
    onto = {l['id']: l for l in client.get('/api/ontology').json()['labels']}
    assert onto['bounded']['paper_count'] == 1
    assert onto['asymptotic']['paper_count'] == int(not rejected)
    assert calls == [1]


