def test_active_job_remains_visible_with_more_than_300_queued(library, monkeypatch, tmp_path):
    client, pid, paper = library
    from backend import main
    monkeypatch.setattr(main, 'DATA_ROOT', tmp_path)
    with connect() as c:
        running = c.execute("INSERT INTO ai_jobs(paper_id,status) VALUES(?,'running')", (pid,)).lastrowid
        for index in range(305):
            other = c.execute("INSERT INTO papers(title,file_hash,page_count,parse_quality,status) VALUES(?,?,1,'good','awaiting_chat')", (f'Queued {index}', f'hash-{index}')).lastrowid
            c.execute("INSERT INTO ai_jobs(paper_id,status) VALUES(?,'queued')", (other,))
    events = tmp_path / 'ai_jobs' / str(running) / 'events.jsonl'
    events.parent.mkdir(parents=True)
    events.write_text('{"message":"Falling back from WebSockets to HTTPS transport. request timed out"}', encoding='utf-8')
    jobs = client.get('/api/ai/jobs').json()
    assert len(jobs) == 300
    assert jobs[0]['id'] == running
    assert 'HTTPS' in jobs[0]['stage']
    assert client.get('/api/ai/queue').json() == {'running': 1, 'queued': 305}


